-- tally schema (system MySQL, database `tally`).
--
-- The records live here rather than in the phone's own storage: the device holds a
-- view, not the only copy, so a wipe or a reinstall costs nothing.
--
-- A delete is a real DELETE. Undo is the client re-creating what it still holds in
-- memory for the length of the snackbar — not a row lingering with a flag on it.
-- Deleting a tally cascades to its entries.

SET NAMES utf8mb4;

-- One thing you are keeping count of: a trip, a job, a month.
CREATE TABLE IF NOT EXISTS tallies (
  id         VARCHAR(40)  NOT NULL PRIMARY KEY,       -- generated by the client, so an
  name       VARCHAR(64)  NOT NULL,                   -- entry can be made before a round trip
  currency   VARCHAR(8)   NOT NULL DEFAULT '₪',
  accent     TINYINT      NOT NULL DEFAULT 0,
  ex_vat     TINYINT      NOT NULL DEFAULT 0,       -- show this tally without VAT
  created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- One movement of money. Amounts are minor units (agorot/cents) — a running
-- balance must never accumulate float error.
CREATE TABLE IF NOT EXISTS entries (
  id         VARCHAR(40)  NOT NULL PRIMARY KEY,
  tally_id   VARCHAR(40)  NOT NULL,
  direction  ENUM('IN','OUT') NOT NULL,
  amount     BIGINT       NOT NULL,
  note       VARCHAR(255) NOT NULL DEFAULT '',
  category   VARCHAR(32)  NOT NULL DEFAULT 'other',
  vat_included TINYINT    NOT NULL DEFAULT 0,       -- VAT sits inside `amount`
  at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_tally (tally_id, at),
  CONSTRAINT fk_entry_tally FOREIGN KEY (tally_id) REFERENCES tallies(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Added after the first release. MySQL has no ADD COLUMN IF NOT EXISTS, and this file
-- has to stay re-runnable, so each one is guarded by the catalogue.
--
-- `amount` is always what was written down — what was actually paid. `vat_included`
-- says whether VAT is sitting inside that number, and `ex_vat` says whether this tally
-- is currently shown with it taken back out. Neither ever changes an amount: the
-- ex-VAT figure is derived at display time, so the record stays the receipt.
SET @sql := (SELECT IF(COUNT(*) = 0,
    'ALTER TABLE entries ADD COLUMN vat_included TINYINT NOT NULL DEFAULT 0 AFTER category',
    'DO 0')
  FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'entries' AND COLUMN_NAME = 'vat_included');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

SET @sql := (SELECT IF(COUNT(*) = 0,
    'ALTER TABLE tallies ADD COLUMN ex_vat TINYINT NOT NULL DEFAULT 0 AFTER accent',
    'DO 0')
  FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tallies' AND COLUMN_NAME = 'ex_vat');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- "Add my last purchase": an entry taken from the card remembers which card purchase
-- it was, so the same purchase is never offered twice. Hand-written entries leave it NULL.
SET @sql := (SELECT IF(COUNT(*) = 0,
    'ALTER TABLE entries ADD COLUMN card_ref VARCHAR(200) NULL AFTER vat_included',
    'DO 0')
  FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'entries' AND COLUMN_NAME = 'card_ref');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- One press of "add my last purchase". It lives here, not in the server's memory, so a
-- server restart while it waits resumes the wait instead of forgetting it.
CREATE TABLE IF NOT EXISTS purchase_watches (
  id           VARCHAR(40)  NOT NULL PRIMARY KEY,
  tally_id     VARCHAR(40)  NOT NULL,
  requested_at TIMESTAMP    NOT NULL,                 -- UTC, written by the server
  status       ENUM('waiting','added','expired','failed','cancelled') NOT NULL DEFAULT 'waiting',
  entry_id     VARCHAR(40)  NULL,
  checks       INT          NOT NULL DEFAULT 0,
  error        VARCHAR(255) NULL,
  KEY idx_tally (tally_id, requested_at),
  CONSTRAINT fk_watch_tally FOREIGN KEY (tally_id) REFERENCES tallies(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Where to wake the phone (UnifiedPush through the suite's ntfy) when a wait ends.
CREATE TABLE IF NOT EXISTS push_endpoints (
  endpoint      VARCHAR(500) NOT NULL PRIMARY KEY,
  registered_at TIMESTAMP    NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- An open tally collects: money another app records (a paid work day counted in
-- countdown) lands in every open tally by itself, until the tally is stopped. Tallies
-- that existed before this column were not collecting, so the column defaults to 0;
-- a NEW tally is created open by the server (lib/tallies.ts saveTally).
SET @sql := (SELECT IF(COUNT(*) = 0,
    'ALTER TABLE tallies ADD COLUMN is_open TINYINT NOT NULL DEFAULT 0 AFTER ex_vat',
    'DO 0')
  FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tallies' AND COLUMN_NAME = 'is_open');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- An entry another app put here names what it came from ("countdown:<tickId>"), so
-- saving that thing again updates the one entry instead of adding a second, and
-- removing it there removes it here. Hand-written entries leave it NULL.
SET @sql := (SELECT IF(COUNT(*) = 0,
    'ALTER TABLE entries ADD COLUMN source_ref VARCHAR(200) NULL AFTER card_ref, ADD UNIQUE KEY uq_source (tally_id, source_ref)',
    'DO 0')
  FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'entries' AND COLUMN_NAME = 'source_ref');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- When the tally last became open. Card purchases made from then on are collected into
-- it automatically (lib/cardCollect.ts); earlier ones are not — opening a tally is not a
-- request to backfill the week.
SET @sql := (SELECT IF(COUNT(*) = 0,
    'ALTER TABLE tallies ADD COLUMN opened_at TIMESTAMP NULL AFTER is_open',
    'DO 0')
  FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tallies' AND COLUMN_NAME = 'opened_at');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;
